// Exercício 5: Calcule a área de um retângulo.

alert("Área de Retângulo");

let larguraRetangulo = parseFloat(prompt("Informe o valor da largura do retângulo em centímetros: "));

let alturaRetangulo = parseFloat(prompt("Informe a altura do retângulo em centímetros: "));

let areaRetangulo = larguraRetangulo * alturaRetangulo;

alert("A área total do retângulo de largura " + larguraRetangulo + "cm e altura " + alturaRetangulo + "cm é: " + areaRetangulo + "cm²");