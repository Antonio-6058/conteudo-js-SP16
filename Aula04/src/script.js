// Operadores de Atribuição

// Operador Atribuidor de Adição
let a = 10;

a += 5; // É o mesmo que a = a + 5;

console.log(a);

console.log("");

// Operador Atribuidor de Subtração
let b = 5;

b -= 1; // É o mesmo que b = b - 1;

console.log(b);

console.log("");

// Operador Atribuidor de Multiplicação
let c = 7;

c *= 2; // É o mesmo que c = c * 2;

console.log(c);

console.log("");

// Operador Atribuidor de Divisão
let d = 8;

d /= 4; // É o mesmo que d = d / 4;

console.log(d);

console.log("");

// Operador Atribuidor de Exponenciação
let e = 100;

e **= 2; // É o mesmo que e = e ** 2;

console.log(e);

console.log("");

// Operador Atribuidor de Resto
let f = 125;

f %= 5; // É o mesmo que f = f % 5;

console.log(f);

console.log("");

// Operador Atribuidor de Adição com String
let saudacao = "Olá, ";

saudacao += "SP16!"; // É o mesmo que saudacao = saudacao + "SP16!"

console.log(saudacao);